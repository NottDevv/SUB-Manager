export function t(key: keyof typeof translations['fa'], lang: Lang, replacements?: Record<string, any>): string {
  let text = translations[lang]?.[key] || translations['fa']?.[key] || key;
  if (replacements) {
    Object.keys(replacements).forEach((k) => {
      text = text.replace(`{${k}}`, String(replacements[k]));
    });
  }
  return text;
}
